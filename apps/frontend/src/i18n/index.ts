// Sync HTML document lang attribute and font classes
export const syncDocumentLanguage = (lng: string) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lng;
    if (lng === 'km') {
      document.documentElement.classList.add('lang-km');
      document.body?.classList.add('font-khmer');
    } else {
      document.documentElement.classList.remove('lang-km');
      document.body?.classList.remove('font-khmer');
    }
  }
};

const initialSavedLng = (typeof localStorage !== 'undefined' && localStorage.getItem('rfm_language')) || 'en';
syncDocumentLanguage(initialSavedLng);

i18n.use(initReactI18next).init({
  resources,
  lng: initialSavedLng,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

i18n.on('languageChanged', (lng) => {
  syncDocumentLanguage(lng);
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('rfm_language', lng);
  }
});

export default i18n;
